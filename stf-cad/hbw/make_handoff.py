    out.append("```")
    out.append("## E. Belegungsplan (terminal -> signal), per module\n")
    for m, d in CTL["modules"].items():
        out.append(f"### {m}: {d['name']} ({d['ft']})\n```")
        out.append(" ".join(f"{k}:{v}" for k, v in sorted(d["st3"].items(), key=lambda kv: int(kv[0]))))
        out.append(f"relays {json.dumps(d.get('relays'))}\nvalves {json.dumps(d.get('valves'))}")
        out.append("```")
    out.append("## F. Components (housing dims and sources)\n")
