def dump(d):
    return "\n".join(f"    {k} = {v!r}" for k, v in d.items())


def parts_table(parts, title):
    rows = [f"\n### {title}\n", "| part | group | frame | kind | p (x,y,z) | size | tag | support |",
            "|---|---|---|---|---|---|---|---|"]
    for p in parts:
        if p.group == "frame":
            continue
        s = p.s if p.kind == "box" else f"{p.s[0]}-axis L{p.s[1]} D{p.s[2]}"
        rows.append(f"| {p.name} | {p.group} | {getattr(p, 'frame', getattr(p, 'joint', ''))} | {p.kind} | "
                    f"{tuple(round(v, 2) for v in p.p)} | {s} | {p.tag} | {p.support} |")
    return "\n".join(rows)


def main():
    out = [NARRATIVE.strip(), "\n\n---\n# Appendices (generated from the models)\n"]
    out.append("## A. Parameter tables\n")
    for name, d in (("hbw_model.P", HM.P), ("vgr_model.V", VG.V), ("oven_model.O", OM.O),
                    ("sorting_model.S", SM.S), ("plc_model.C", PM.C)):
        out.append(f"### {name}\n```\n{dump(d)}\n```")
    out.append("## B. Factory placement\n```")
    out.append(f"table PLATE = {FL.PLATE}")
    out.append(f"HBW   rot +90  TX, TY = {FL.TX}, {FL.TY}   rect {FL.module_rect()}")
    out.append(f"VGR   translate VGR_AT = {FL.VGR_AT}          rect {FL.vgr_rect()}  tower {FL.vgr_tower()}")
    out.append(f"OVEN  rot +{FL.OVEN_ROT}  TX, TY = {FL.OVEN_TX}, {FL.OVEN_TY}  rect {FL.oven_rect()}")
    out.append(f"SORT  rot +{FL.SORT_ROT}  TX, TY = {FL.SORT_TX}, {FL.SORT_TY}  rect {FL.sort_rect()}")
    out.append(f"PLC   translate PLC_AT = {FL.PLC_AT}           rect {FL.plc_rect()}")
    out.append("```")
    out.append("## C. VGR stations (solved)\n```")
    for k, v in FL.stations().items():
        out.append(f"{k:10s} {v}")
    out.append("```")
    out.append("## D. Joints and proven stops\n```")
    out.append(f"oven STATIONS (turn deg) = {OM.STATIONS}; AXES = {OM.AXES}")
    out.append(f"oven SLIDER {OM.O['SLIDER']} DOOR_Z {OM.O['DOOR_Z']} SAUGER {OM.O['SAUGER']} "
               f"LOWER {OM.O['LOWER']} PUSH {OM.O['PUSH']}")
    out.append(f"sorting EJECT {SM.S['EJECT']} axis {SM.EJECT_AXIS}; Lagerstellen {SM.handover_points()}")
