"""
DT-4a: compile the STF-2 PLC program for the software-in-the-loop: plc/*.st -> port.py (portable IEC 61131-3)
-> MatIEC iec2c (C) -> clang -> a native library the plant drives scan by scan (runtime.py).

    .venv-twin/bin/python -m twin.sil.build        (from stf-cad/line2) -> twin/out/sil/

The runtime written here (glue.c) gives every LOCATED variable its own storage and a table (address, type, pointer)
so the plant reads / writes the I/O image by name; it advances the IEC clock one task interval (10 ms) per scan.
MatIEC is the compiler inside OpenPLC and Beremiz, built from source (STF_MATIEC, as cell 1's sil/build.py on main).
"""
