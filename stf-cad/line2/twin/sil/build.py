sys.path.insert(0, HERE)
import port                                                 # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "out", "sil")
MATIEC = os.environ.get("STF_MATIEC", os.path.expanduser("~/workspace/stf-hw/.cache/matiec"))
CLANG = os.environ.get("STF_CC", "clang")
CTYPE = {"BOOL": "BOOL", "INT": "INT", "LREAL": "LREAL", "UDINT": "UDINT"}


def address(area, size, a, b):
    return f"%{area}{size}{a}" + (f".{b}" if b != "" else "")


# read-only monitors of the program's internal state (what an HMI reads over ADS): (name, C expression on PLC__RUN)
MONITOR = [("fbOven.bReady", "FBOVEN.BREADY.value"), ("fbOven.bHold", "FBOVEN.BHOLD.value"),
           ("fbSafety.bRunEnable", "FBSAFETY.BRUNENABLE.value")] + \
    [(f"fbOven.aDuty[{k}]", f"FBOVEN.ADUTY.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aSp[{k}]", f"FBOVEN.ASP.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aW0[{k}]", f"FBOVEN.AW0.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aA1[{k}]", f"FBOVEN.AA1.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aElementAlarm[{k}]", f"FBOVEN.AELEMENTALARM.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aPhAlarm[{k}]", f"FBOVEN.APHALARM.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aBroken[{i}]", f"FBOVEN.ABROKEN.value.table[{i}].value") for i in range(9)] + \
    [(f"fbBand.aZoneContent[{k}]", f"FBBAND.AZONECONTENT.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aI[{k}]", f"FBOVEN.AI.value.table[{k}].value") for k in range(3)] + \
    [(f"fbOven.aLost[{k}]", f"FBOVEN.ALOST.value.table[{k}].value") for k in range(3)]


def glue(located):
    L = ["/* generated by twin/sil/build.py: storage + a lookup table for every located variable */",
         '#include "iec_std_lib.h"']
    for typ, cname, *_ in located:
        L += [f"static {typ} {cname}_v;", f"{typ} *{cname} = &{cname}_v;"]
    L += [f"int plc_count(void) {{ return {len(located)}; }}",
          "static const char *names_[] = {" + ", ".join(f'"{address(*x[2:])}"' for x in located) + "};",
          "static const char *types_[] = {" + ", ".join(f'"{x[0]}"' for x in located) + "};",
          "static void *ptrs_[] = {" + ", ".join(f"&{x[1]}_v" for x in located) + "};",
          "const char *plc_name(int i) { return names_[i]; }",
          "const char *plc_type(int i) { return types_[i]; }",
          "void *plc_ptr(int i) { return ptrs_[i]; }",
          "TIME __CURRENT_TIME;",
          "extern unsigned long long common_ticktime__;",
          "void config_init__(void);",
          "void config_run__(unsigned long tick);",
          "static unsigned long tick_;",
          "void plc_init(void) { tick_ = 0; __CURRENT_TIME.tv_sec = 0; __CURRENT_TIME.tv_nsec = 0; config_init__(); }",
          "void plc_scan(void) {",
          "  config_run__(tick_++);",
          "  __CURRENT_TIME.tv_nsec += common_ticktime__;",
          "  while (__CURRENT_TIME.tv_nsec >= 1000000000) { __CURRENT_TIME.tv_nsec -= 1000000000; __CURRENT_TIME.tv_sec++; }",
          "}",
          "unsigned long long plc_tick_ns(void) { return common_ticktime__; }", ""]
    return "\n".join(L)


def monitor_c(ret=()):
    """mon.c: the monitors + the retained memory (a power cycle), with the resource file's preamble."""
    size = " + ".join(f"sizeof(PLC__RUN.{c})" for c, _ in ret) or "0"
    save = [f"  memcpy(b, &PLC__RUN.{c}, sizeof(PLC__RUN.{c})); b += sizeof(PLC__RUN.{c});" for c, _ in ret]
    load = [f"  memcpy(&PLC__RUN.{c}, b, sizeof(PLC__RUN.{c})); b += sizeof(PLC__RUN.{c});" for c, _ in ret]
    return "\n".join(["#include <string.h>",
                      f"int plc_retain_size(void) {{ return {size}; }}",
                      "void plc_retain_save(unsigned char *b) {"] + save + ["}",
                      "void plc_retain_load(const unsigned char *b) {"] + load + ["}"]) + "\n" + "\n".join(["/* generated by twin/sil/build.py: read-only monitors of the program's state */",
                      '#include "iec_std_lib.h"', '#include "accessor.h"', '#include "POUS.h"',
                      "extern MAIN_data__ PLC__RUN;",
                      f"int plc_mon_count(void) {{ return {len(MONITOR)}; }}", "double plc_mon(int i) {",
                      "  switch (i) {"] +
                     [f"    case {i}: return (double)PLC__RUN.{expr};" for i, (_, expr) in enumerate(MONITOR)] +
                     ["  }", "  return 0.0;", "}", ""])


def retained(src):
    """[(C path on PLC__RUN, IEC name)] of every VAR RETAIN variable of the FB instances MAIN declares."""
    fb_vars = {}
    for m in re.finditer(r"^FUNCTION_BLOCK\s+(\w+)(.*?)^END_FUNCTION_BLOCK", src, re.M | re.S):
        names = []
        for blk in re.finditer(r"VAR RETAIN(.*?)END_VAR", m.group(2), re.S):
            body = re.sub(r"\(\*.*?\*\)", "", blk.group(1), flags=re.S)
            for decl in body.split(";"):
                if ":" in decl:
                    names += [n.strip() for n in decl.split(":")[0].split(",") if n.strip()]
        if names:
            fb_vars[m.group(1)] = names
    main = re.search(r"^PROGRAM MAIN(.*?)^END_PROGRAM", src, re.M | re.S).group(1)
    out = []
    for inst, fb in re.findall(r"^\s*(\w+)\s*:\s*(FB_\w+)\s*;", main, re.M):
        for v in fb_vars.get(fb, []):
            out.append((f"{inst.upper()}.{v.upper()}", f"{inst}.{v}"))
    return out


def build(out=OUT, plc_dir=None):
    """plc_dir: compile another copy of plc/ (the gate's mutants)."""
    if plc_dir:
        port.PLC = plc_dir
    iec2c = os.path.join(MATIEC, "iec2c")
    if not os.path.exists(iec2c):
        raise SystemExit(f"missing {iec2c}: build MatIEC (twin/MAC_SETUP.md section 5)")
    src, info = port.project()
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    open(os.path.join(out, "stf2_plc.st"), "w").write(src)
    r = subprocess.run([iec2c, "-I", os.path.join(MATIEC, "lib"), "stf2_plc.st"], cwd=out, capture_output=True,
                       text=True)
    if r.returncode != 0:
        raise SystemExit("MatIEC rejected the program:\n" + r.stdout + r.stderr)
    warnings = [ln for ln in (r.stdout + r.stderr).split("\n") if "warning" in ln.lower()]
    located = re.findall(r"__LOCATED_VAR\((\w+),(\w+),(\w),(\w),(\d+)(?:,(\d+))?\)",
                         open(os.path.join(out, "LOCATED_VARIABLES.h")).read())
    open(os.path.join(out, "glue.c"), "w").write(glue(located))
    ret = retained(src)
    mon = monitor_c(ret).split("\n")
    head = ['#include "iec_std_lib.h"', '#include "accessor.h"', '#include "POUS.h"', "extern MAIN_data__ PLC__RUN;"]
    open(os.path.join(out, "mon.c"), "w").write("\n".join(head + [ln for ln in mon if ln not in head]) + "\n")
    c_files = ["glue.c", "mon.c"] + sorted(f for f in os.listdir(out) if f.endswith(".c")
                                           and f not in ("glue.c", "mon.c", "POUS.c"))
    lib = os.path.join(out, "libstf2plc.dylib")
    r = subprocess.run([CLANG, "-shared", "-fPIC", "-O2", "-w", "-I", os.path.join(MATIEC, "lib", "C"), "-I", ".",
                        "-o", lib, *c_files], cwd=out, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("clang failed:\n" + r.stdout + r.stderr)
    by_loc = {loc: n for n, t, loc in info["gvl"] if loc}
    for line in src.split("\n"):                             # the SIL axis variables (R5) are in the configuration
        m = re.match(r"\s+(sil_\w+) AT (%\w+(?:\.\d+)?) : (\w+);", line)
        if m:
            by_loc[m.group(2)] = m.group(1)
    io = {}
    for typ, cname, area, size, a, b in located:
        adr = address(area, size, a, b)
        io[by_loc.get(adr, adr)] = dict(address=adr, type=typ)
    meta = dict(compiler=subprocess.run([iec2c, "-v"], capture_output=True, text=True).stdout.split("\n")[0],
                st_lines=src.count("\n"), located=len(located), io=io, warnings=warnings,
                pous=info["pous"], stubs=info.get("stubs", []), excluded=info["excluded"],
                expanded=info.get("expanded", []), scan_ms=port.SCAN_MS, monitor=[m for m, _ in MONITOR],
                retain=[n for _, n in ret],
                lib_sha=hashlib.sha256(open(lib, "rb").read()).hexdigest()[:16])
    json.dump(meta, open(os.path.join(out, "plc.json"), "w"), indent=1)
    return meta


if __name__ == "__main__":
    m = build()
    print(f"compiled: {m['st_lines']} lines of IEC 61131-3 -> libstf2plc.dylib {m['lib_sha']} ({m['compiler']}); "
          f"{m['located']} located variables; {len(m['warnings'])} warnings; stubs: {', '.join(m['stubs'])}")
